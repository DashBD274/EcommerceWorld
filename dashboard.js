// ================= Safe localStorage =================
function safeGet(key) {
    try { return localStorage.getItem(key); } catch (e) { return null; }
}
function safeSet(key, value) {
    try { localStorage.setItem(key, value); } catch (e) {}
}

// ================= ভাষা প্রয়োগ =================
function applyDashLanguage(lang) {
    const elements = document.querySelectorAll('[data-key]');
    elements.forEach(el => {
        const key = el.getAttribute('data-key');
        if (dashTranslations[lang] && dashTranslations[lang][key]) {
            el.textContent = dashTranslations[lang][key];
        }
    });
}

// ================= RTL =================
const rtlLanguages = ['ar', 'fa'];
function applyDashDirection(lang) {
    if (rtlLanguages.includes(lang)) {
        document.body.classList.add('rtl');
        document.documentElement.setAttribute('dir', 'rtl');
    } else {
        document.body.classList.remove('rtl');
        document.documentElement.setAttribute('dir', 'ltr');
    }
}

// ================= প্রাথমিক ভাষা লোড =================
const savedLang = safeGet('language') || 'en';
applyDashLanguage(savedLang);
applyDashDirection(savedLang);

// ================= থিম =================
const dashThemeToggle = document.getElementById('dashThemeToggle');
const dashThemeIcon = dashThemeToggle ? dashThemeToggle.querySelector('i') : null;

function applyDashTheme(isDark) {
    if (isDark) {
        document.body.classList.add('dark-mode');
        if (dashThemeIcon) {
            dashThemeIcon.classList.remove('fa-moon');
            dashThemeIcon.classList.add('fa-sun');
        }
        const meta = document.querySelector('meta[name="theme-color"]');
        if (meta) meta.setAttribute('content', '#0f172a');
    } else {
        document.body.classList.remove('dark-mode');
        if (dashThemeIcon) {
            dashThemeIcon.classList.remove('fa-sun');
            dashThemeIcon.classList.add('fa-moon');
        }
        const meta = document.querySelector('meta[name="theme-color"]');
        if (meta) meta.setAttribute('content', '#f5f5f5');
    }
}

const savedTheme = safeGet('theme');
applyDashTheme(savedTheme === 'dark');

if (dashThemeToggle) {
    let lastTap = 0;
    dashThemeToggle.addEventListener('click', function(e) {
        e.preventDefault();
        e.stopPropagation();
        const now = Date.now();
        if (now - lastTap < 300) return;
        lastTap = now;
        const isDark = !document.body.classList.contains('dark-mode');
        applyDashTheme(isDark);
        safeSet('theme', isDark ? 'dark' : 'light');
    });
}

// ================= ভাষা সিলেক্ট (Dashboard) =================
const dashLangSelect = document.getElementById('dashLanguageSelect');
if (dashLangSelect) {
    dashLangSelect.value = savedLang;
    dashLangSelect.addEventListener('change', function() {
        const newLang = this.value;
        safeSet('language', newLang);
        applyDashLanguage(newLang);
        applyDashDirection(newLang);
    });
}
